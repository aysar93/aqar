  static LatLng? cityCenter(String? city) {
    if (city == null || city == AnbarLocations.other) {
      return null;
    }

    return cityCenters[city];
  }

  static LatLng? exactAreaCenter({
    required String? city,
    required String? area,
  }) {
    if (city == null ||
        area == null ||
        city == AnbarLocations.other ||
        area == AnbarLocations.other) {
      return null;
    }

    return areaCenters[city]?[area];
  }

  /// يعيد مركز المنطقة إن كان معروفًا.
  /// وإذا لم يكن معروفًا يعيد مركز المدينة.
  static LatLng? locationCenter({
    required String? city,
    required String? area,
  }) {
    final areaCenter = exactAreaCenter(
      city: city,
      area: area,
    );

    if (areaCenter != null) {
      return areaCenter;
    }

    return cityCenter(city);
  }

  static bool hasExactAreaCoordinates({
    required String? city,
    required String? area,
  }) {
    return exactAreaCenter(
          city: city,
          area: area,
        ) !=
        null;
  }

  static double zoomFor({
    required String? city,
    required String? area,
  }) {
    if (hasExactAreaCoordinates(
      city: city,
      area: area,
    )) {
      return areaZoom;
    }

    return cityZoom;
  }
