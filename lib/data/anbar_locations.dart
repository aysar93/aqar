  static List<String> areasForCity(String? city) {
    final normalizedCity = normalizeCity(city);

    if (normalizedCity == null) {
      if (normalizeText(city) == normalizeText(other)) {
        return const [other];
      }

      return const [];
    }

    return List<String>.unmodifiable(
      areasByCity[normalizedCity] ?? const <String>[other],
    );
  }

  static List<String> areasForCityWithAll(String? city) {
    return [allAreas, ...areasForCity(city)];
  }

  static List<String> subdistrictsForCity(String? city) {
    final normalizedCity = normalizeCity(city);

    if (normalizedCity == null) {
      return const [];
    }

    return List<String>.unmodifiable(
      subdistrictsByCity[normalizedCity] ?? const <String>[],
    );
  }

  static bool containsCity(String? city) {
    final value = normalizeText(city);

    if (value == normalizeText(other)) {
      return true;
    }

    return normalizeCity(city) != null;
  }

  static bool containsArea({required String? city, required String? area}) {
    final areaValue = normalizeText(area);

    if (areaValue.isEmpty) {
      return false;
    }

    if (areaValue == normalizeText(other)) {
      return true;
    }

    if (normalizeText(city) == normalizeText(other)) {
      return areaValue == normalizeText(other);
    }

    final normalizedCity = normalizeCity(city);

    if (normalizedCity == null) {
      return false;
    }

    final areas = areasByCity[normalizedCity] ?? const <String>[];

    return areas.any((item) => normalizeText(item) == areaValue);
  }

  static String? normalizeCity(String? city) {
    final value = normalizeText(city);

    if (value.isEmpty || value == normalizeText(allCities) || value == 'الكل') {
      return null;
    }

    if (value == normalizeText(other)) {
      return other;
    }

    for (final item in cities) {
      if (normalizeText(item) == value) {
        return item;
      }
    }

    return _cityAliases[value];
  }

  static String normalizeArea({required String? city, required String? area}) {
    final value = normalizeText(area);

    if (value.isEmpty || value == normalizeText(allAreas) || value == 'الكل') {
      return '';
    }

    if (value == normalizeText(other)) {
      return other;
    }

    final normalizedCity = normalizeCity(city);

    if (normalizedCity == null) {
      return _cleanDisplayText(area);
    }

    final areas = areasByCity[normalizedCity] ?? const <String>[];

    for (final item in areas) {
      if (normalizeText(item) == value) {
        return item;
      }
    }

    final alias = _areaAliases[normalizedCity]?[value];
    if (alias != null) {
      return alias;
    }

    return _cleanDisplayText(area);
  }

  static List<String> get allAreasList {
    final values = <String>{};

    for (final areas in areasByCity.values) {
      values.addAll(areas);
    }

    final result = values.toList()
      ..sort((a, b) => normalizeText(a).compareTo(normalizeText(b)));

    return List<String>.unmodifiable(result);
  }

  static String normalizeText(String? value) {
    if (value == null) {
      return '';
    }

    var text = value.trim();

    if (text.isEmpty) {
      return '';
    }

    text = text
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ٱ', 'ا')
        .replaceAll('ى', 'ي')
        .replaceAll('ة', 'ه')
        .replaceAll('ـ', '');

    text = text.replaceAll(RegExp(r'[\u064B-\u065F\u0670]'), '');

    text = text.replaceAll(RegExp(r'\s+'), ' ');

    return text.trim();
  }

